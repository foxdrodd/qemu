#!/usr/bin/env python3
"""Generate tcg/tci-direct-call.c.inc: typed helper calls for TCI.

TCI normally calls helpers through libffi.  Where that is slow (Emscripten,
whose libffi port goes through JavaScript), tcg/tci.c instead switches on
the helper's signature id (TCI_SIG in include/tcg/helper-info.h) and calls
the helper through a function pointer of the exact type.  Arguments are
32- or 64-bit integers, so all signatures with up to 7 arguments are
enumerated here.

SPDX-License-Identifier: GPL-2.0-or-later
"""
import sys

MAX_ARGS = 7
RET = {0: "void", 1: "uint32_t", 2: "uint64_t"}

out = ["/* Generated by scripts/tci-direct-call.py, do not edit. */"]
for r, rtype in RET.items():
    for n in range(MAX_ARGS + 1):
        for m in range(1 << n):
            types = ["uint64_t" if m >> i & 1 else "uint32_t"
                     for i in range(n)]
            proto = ", ".join(types) or "void"
            args = ", ".join(f"stack[{i}]" for i in range(n))
            call = f"(({rtype} (*)({proto}))func)({args})"
            if r:
                call = f"regs[TCG_REG_R0] = {call}"
            out.append(f"case TCI_SIG({r}, {n}, {m:#x}): {call}; break;")
sys.stdout.write("\n".join(out) + "\n")
